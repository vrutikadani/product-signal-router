"""Replay the synthetic world and write evals/report.json and evals/REPORT.md.

Usage: python evals/run_eval.py [--check]
--check fails if the report on disk is out of date or a guardrail is broken.
"""
from __future__ import annotations

import json
import sys
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from expansion_signals.evaluation import measure, replay  # noqa: E402
from expansion_signals.synthetic import generate  # noqa: E402

START, END = date(2026, 4, 15), date(2026, 6, 30)
LATE = (date(2026, 6, 10), date(2026, 6, 11))


def build() -> dict:
    accounts, events = generate()
    rp = replay(accounts, events, START, END, late_days=LATE)
    return measure(accounts, rp, START, END, events)


def to_markdown(r: dict) -> str:
    lines = [
        "# Evaluation report (synthetic)",
        "",
        "Generated by `python evals/run_eval.py`. Outcomes come from the synthetic archetypes, so these",
        "numbers show that the measurement works. They say nothing about how well these signals predict",
        "expansion in a real business.",
        "",
        f"- Logic version: `{r['logic_version']}`; replay window {r['window'][0]} to {r['window'][1]}",
        f"- Accounts: {r['accounts']}; signals delivered: {r['signals_delivered']} "
        f"({r['accounts_surfaced']} unique accounts)",
        f"- Precision (expanded within 60 days of a delivered signal): **{r['precision_60d']}** per signal, "
        f"{r['precision_60d_by_account']} per account",
        f"- Recall (eligible expansions surfaced in the 60 days before): **{r['recall_60d']}** "
        f"of {r['eligible_expansions']}",
        f"- Expansions excluded because Sales already had an open opportunity: {r['expansions_already_engaged']}",
        f"- Median lead time, first signal to expansion: {r['median_lead_time_days']} days",
        "",
        "## Why expansions were missed",
        "",
        "| Cause | Count |",
        "|---|---|",
    ]
    lines += [f"| {k} | {v} |" for k, v in r["miss_causes"].items()]
    ca = r["coverage_audit"]
    lines += ["", "## Coverage audit (no outcomes needed)", "",
              f"Top 10% of accounts by 30-day consumption with no signal, no open opportunity and no two-way "
              f"seller conversation: **{ca['listed']}** accounts. It contains {ca['contains_missed_large_steady']} "
              f"of the {ca['missed_large_steady']} large steady accounts the signals missed; "
              f"{ca['listed_that_expanded']} of the listed accounts expanded."]
    lines += ["", "## By archetype", "",
              "| Archetype | Accounts | Signals delivered | Eligible expansions | Caught |", "|---|---|---|---|---|"]
    lines += [f"| {k} | {v['accounts']} | {v['signals_delivered']} | {v['eligible_expansions']} | {v['caught']} |"
              for k, v in r["by_archetype"].items()]
    lines += ["", "## Operations", "",
              f"- Seller responses: {r['signal_status']}",
              f"- Dismiss reasons: {r['dismiss_reasons']}",
              f"- Account-days suppressed because a seller had dismissed: {r['account_days_suppressed_by_dismissal']}",
              f"- Account-days held because the owner was at weekly capacity: {r['account_days_held_for_capacity']}",
              f"- Late warehouse days {', '.join(r['late_warehouse_days'])}: "
              f"{r['account_days_held_for_late_data']} account-days held instead of decided",
              f"- Decisions over all account-days: {r['decision_days']}", ""]
    return "\n".join(lines)


def main() -> int:
    r = build()
    out_json = ROOT / "evals" / "report.json"
    out_md = ROOT / "evals" / "REPORT.md"
    text = json.dumps(r, indent=2, sort_keys=True) + "\n"
    if "--check" in sys.argv:
        ok = out_json.exists() and out_json.read_text() == text
        if not ok:
            print("evals/report.json is out of date; run python evals/run_eval.py")
            return 1
        print("report up to date")
        return 0
    out_json.write_text(text)
    out_md.write_text(to_markdown(r))
    print(to_markdown(r))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
